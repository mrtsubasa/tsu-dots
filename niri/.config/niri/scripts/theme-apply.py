def parse_toml_colors(path: Path) -> dict[str, str]:
    raw = path.read_text(encoding="utf-8", errors="replace")
    out: dict[str, str] = {}
    for line in raw.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("["):
            continue
        m = re.match(r'^([a-zA-Z0-9_]+)\s*=\s*"?(#[0-9a-fA-F]{3,8}|dark|light)"?\s*$', line)
        if not m:
            m = re.match(r'^([a-zA-Z0-9_]+)\s*=\s*"([^"]+)"\s*$', line)
            if not m:
                continue
            key, val = m.group(1), m.group(2)
            out[key] = val
            continue
        out[m.group(1)] = m.group(2)
    return out


def c(colors: dict[str, str], *keys: str, fallback: str = "#888888") -> str:
    for k in keys:
        v = colors.get(k)
        if v and v.startswith("#"):
            return v
    return fallback


