def find_theme(name: str) -> Path | None:
    for root in (USER_THEMES, THEMES):
        p = root / name
        if (p / "colors.toml").is_file():
            return p
    return None


def list_themes() -> list[str]:
    names: set[str] = set()
    for root in (USER_THEMES, THEMES):
        if not root.is_dir():
            continue
        for d in root.iterdir():
            if d.is_dir() and (d / "colors.toml").is_file():
                names.add(d.name)
    return sorted(names)


def pick_background(theme_dir: Path) -> Path | None:
    bg_dir = theme_dir / "backgrounds"
    if not bg_dir.is_dir():
        return None
    imgs = sorted(
        [
            p
            for p in bg_dir.iterdir()
            if p.suffix.lower() in {".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"}
        ]
    )
    return imgs[0] if imgs else None


def apply(name: str, with_wallpaper: bool = True) -> int:
    theme_dir = find_theme(name)
    if not theme_dir:
        print(f"Thème inconnu: {name}", file=sys.stderr)
        return 1

    colors = parse_toml_colors(theme_dir / "colors.toml")
    if not colors:
        print(f"colors.toml vide: {theme_dir}", file=sys.stderr)
        return 1

    STATE.mkdir(parents=True, exist_ok=True)
    if CURRENT.exists() or CURRENT.is_symlink():
        CURRENT.unlink()
    CURRENT.symlink_to(theme_dir)
    NAME_FILE.write_text(name + "\n", encoding="utf-8")

    (HOME / ".config/waybar").mkdir(parents=True, exist_ok=True)
    (HOME / ".config/waybar/colors.css").write_text(waybar_css(colors), encoding="utf-8")

    gtk3 = HOME / ".config/gtk-3.0"
    gtk4 = HOME / ".config/gtk-4.0"
    gtk3.mkdir(parents=True, exist_ok=True)
    gtk4.mkdir(parents=True, exist_ok=True)
    gcss = gtk_css(colors)
    (gtk3 / "colors.css").write_text(gcss, encoding="utf-8")
    (gtk4 / "colors.css").write_text(gcss, encoding="utf-8")

    kitty_dir = HOME / ".config/kitty"
    kitty_dir.mkdir(parents=True, exist_ok=True)
    (kitty_dir / "current-theme.conf").write_text(kitty_conf(colors), encoding="utf-8")

    alacritty_dir = HOME / ".config/alacritty"
    alacritty_dir.mkdir(parents=True, exist_ok=True)
    (alacritty_dir / "current-theme.toml").write_text(alacritty_toml(colors), encoding="utf-8")

    mode = colors.get("mode", "dark")
    try:
        scheme = "prefer-light" if mode == "light" else "prefer-dark"
        subprocess.run(
            ["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", scheme],
            check=False,
            capture_output=True,
        )
    except Exception:
        pass

    palette = HOME / ".config/niri/scripts/palette-apply.sh"
    if palette.is_file():
        subprocess.run(["bash", str(palette)], check=False)

    if with_wallpaper:
        wall = pick_background(theme_dir)
        wall_script = HOME / ".config/niri/scripts/wallpaper.sh"
        if wall and wall_script.is_file():
            subprocess.run(["bash", str(wall_script), "set", str(wall)], check=False)

    meta = {"name": name, "path": str(theme_dir), "mode": mode, "accent": c(colors, "accent", "blue")}
    (STATE / "theme.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(name)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Applique un pack thème Omarchy sur le rice Niri")
    ap.add_argument("command", choices=["list", "apply", "current"])
    ap.add_argument("name", nargs="?")
    ap.add_argument("--no-wallpaper", action="store_true")
    args = ap.parse_args()

    if args.command == "list":
        for n in list_themes():
            print(n)
        return 0
    if args.command == "current":
        if NAME_FILE.is_file():
            print(NAME_FILE.read_text(encoding="utf-8").strip())
            return 0
        print("")
        return 0
    if args.command == "apply":
        if not args.name:
            print("Usage: theme-apply.py apply <name>", file=sys.stderr)
            return 2
        return apply(args.name, with_wallpaper=not args.no_wallpaper)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
